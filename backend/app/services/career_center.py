"""Career Center analytics: outcomes, engagement, caseload risk and advisor briefs.

All numbers are deterministic counts over stored records. Nothing here is
generated by a language model, and every risk flag has a written rule.
"""
from __future__ import annotations

import csv
import io
from collections import Counter, defaultdict
from datetime import datetime, timedelta
from statistics import median

from app.api.mock_store import InMemoryStore

POSITIVE_OUTCOMES = {"full_time", "internship", "grad_school", "military_service"}
OUTCOME_LABELS = {
    "full_time": "Full-time job",
    "internship": "Internship / co-op",
    "grad_school": "Graduate school",
    "military_service": "Military / service",
    "still_seeking": "Still seeking",
    "not_seeking": "Not seeking",
}
# Advisor time an activity would otherwise take, in hours (stated assumptions).
ADVISOR_HOURS = {"resume_analyzed": 0.25, "interview_practiced": 0.5, "mission_completed": 0.1}
ACTIVE_DAYS = 30
ENGAGED_MIN_ACTIONS = 3


def _parse(ts: str | None) -> datetime | None:
    if not ts:
        return None
    try:
        return datetime.fromisoformat(ts.replace("Z", "+00:00")).replace(tzinfo=None)
    except ValueError:
        return None


def _rate(numerator: int, denominator: int) -> float | None:
    return round(100 * numerator / denominator, 1) if denominator else None


def _is_graduating(student: dict, now: datetime) -> bool:
    """Seniors and anyone whose graduation year is this year or earlier."""
    if str(student.get("year", "")).lower() == "senior":
        return True
    grad = str(student.get("graduation_date") or "")
    digits = [int(part) for part in grad.split() if part.isdigit() and len(part) == 4]
    return bool(digits) and digits[0] <= now.year


class CareerCenterAnalytics:
    """Computes console views for one scope (demo cohort or live students)."""

    def __init__(self, store: InMemoryStore, demo: bool, now: datetime | None = None):
        self.store = store
        self.demo = demo
        self.now = now or datetime.utcnow()
        self.students = {
            sid: s for sid, s in store.students.items() if bool(s.get("is_demo")) == demo
        }
        self.activities = [a for a in store.activities if a["student_id"] in self.students]
        self.outcomes = {sid: o for sid, o in store.outcomes.items() if sid in self.students}
        self.events = {eid: e for eid, e in store.campus_events.items() if bool(e.get("is_demo")) == demo}
        # Attendance totals count every check-in for an event; per-student views stay in scope.
        self.event_checkins = [c for c in store.checkins if c["event_id"] in self.events]
        self.checkins = [c for c in self.event_checkins if c["student_id"] in self.students]
        self._by_student: dict[str, list[dict]] = defaultdict(list)
        for activity in self.activities:
            self._by_student[activity["student_id"]].append(activity)

    # ── Per-student helpers ─────────────────────────────────────────────

    def activity_counts(self, student_id: str) -> Counter:
        return Counter(a["kind"] for a in self._by_student.get(student_id, []))

    def last_active(self, student_id: str) -> datetime | None:
        times = [_parse(a["timestamp"]) for a in self._by_student.get(student_id, [])]
        times = [t for t in times if t]
        return max(times) if times else None

    def engagement_score(self, student_id: str) -> int:
        counts = self.activity_counts(student_id)
        score = (
            10 * min(counts["plan_generated"], 1)
            + 8 * min(counts["resume_analyzed"], 3)
            + 10 * min(counts["interview_practiced"], 3)
            + 4 * min(counts["mission_added"], 3)
            + 6 * min(counts["mission_completed"], 3)
            + 8 * min(counts["event_checkin"], 3)
        )
        return min(100, score)

    def risk_flags(self, student_id: str) -> list[str]:
        student = self.students[student_id]
        counts = self.activity_counts(student_id)
        summary = self.store.plan_summaries.get(student_id, {})
        last = self.last_active(student_id)
        year = str(student.get("year", "")).lower()
        flags = []
        if _is_graduating(student, self.now) and student_id not in self.outcomes:
            flags.append("Graduating with no outcome reported")
        if student_id in self.outcomes and self.outcomes[student_id].get("outcome_type") == "still_seeking":
            flags.append("Reported still seeking")
        if last is None or last < self.now - timedelta(days=ACTIVE_DAYS):
            flags.append(f"No activity in {ACTIVE_DAYS} days")
        if year in {"junior", "senior"} and counts["interview_practiced"] == 0:
            flags.append("No interview practice yet")
        if summary.get("resume_score") is not None and summary["resume_score"] < 60:
            flags.append("Resume score below 60")
        if summary.get("profile_strength") is not None and summary["profile_strength"] < 40:
            flags.append("Profile strength below 40")
        outcome = self.outcomes.get(student_id)
        if outcome and outcome.get("outcome_type") == "full_time" and not outcome.get("degree_required"):
            flags.append("Employed in a role that may not need a degree")
        return flags

    @staticmethod
    def priority(flags: list[str]) -> str:
        urgent = {"Graduating with no outcome reported", "Reported still seeking",
                  "Employed in a role that may not need a degree"}
        if len(flags) >= 3 or (urgent & set(flags) and len(flags) >= 2):
            return "high"
        return "medium" if flags else "low"

    # ── Overview ─────────────────────────────────────────────────────────

    def overview(self) -> dict:
        students = self.students
        total = len(students)
        activated = [sid for sid in students if self._by_student.get(sid)]
        active_cutoff = self.now - timedelta(days=ACTIVE_DAYS)
        active_30 = [sid for sid in activated if (self.last_active(sid) or datetime.min) >= active_cutoff]
        kinds = Counter(a["kind"] for a in self.activities)

        graduating = [sid for sid, s in students.items() if _is_graduating(s, self.now)]
        grad_outcomes = [self.outcomes[sid] for sid in graduating if sid in self.outcomes]
        placed = [o for o in grad_outcomes if o.get("outcome_type") in POSITIVE_OUTCOMES]
        employed = [o for o in grad_outcomes if o.get("outcome_type") == "full_time"]
        degree_level = [o for o in employed if o.get("degree_required")]
        salaries = [o["salary"] for o in employed if o.get("salary") and o.get("degree_required")]

        engaged = {sid for sid in students if len(self._by_student.get(sid, [])) >= ENGAGED_MIN_ACTIONS}

        def placement_for(group: set[str]) -> dict:
            reports = [self.outcomes[sid] for sid in graduating if sid in group and sid in self.outcomes]
            return {
                "reported": len(reports),
                "placement_rate": _rate(sum(o.get("outcome_type") in POSITIVE_OUTCOMES for o in reports), len(reports)),
            }

        hours = sum(ADVISOR_HOURS.get(kind, 0) * count for kind, count in kinds.items())

        return {
            "scope": "demo" if self.demo else "live",
            "generated_at": self.now.isoformat(),
            "students": {
                "total": total,
                "activated": len(activated),
                "activation_rate": _rate(len(activated), total),
                "active_30_days": len(active_30),
            },
            "engagement": {
                "plans_generated": kinds["plan_generated"],
                "resume_analyses": kinds["resume_analyzed"],
                "interview_practices": kinds["interview_practiced"],
                "missions_added": kinds["mission_added"],
                "missions_completed": kinds["mission_completed"],
                "event_checkins": len(self.checkins),
                "events_tracked": len(self.events),
            },
            "outcomes": {
                "graduating_students": len(graduating),
                "outcomes_reported": len(grad_outcomes),
                "knowledge_rate": _rate(len(grad_outcomes), len(graduating)),
                "placement_rate": _rate(len(placed), len(grad_outcomes)),
                "degree_level_rate": _rate(len(degree_level), len(employed)),
                "median_degree_level_salary": int(median(salaries)) if salaries else None,
                "breakdown": [
                    {"outcome_type": key, "label": OUTCOME_LABELS[key],
                     "count": sum(o.get("outcome_type") == key for o in grad_outcomes)}
                    for key in OUTCOME_LABELS
                ],
            },
            "engaged_vs_not": {
                "definition": f"Engaged = {ENGAGED_MIN_ACTIONS}+ recorded actions. This is a correlation, not proof of cause.",
                "engaged": placement_for(engaged),
                "not_engaged": placement_for(set(students) - engaged),
            },
            "advisor_capacity": {
                "hours_saved_estimate": round(hours, 1),
                "assumptions": {kind: f"{h} h per action" for kind, h in ADVISOR_HOURS.items()},
            },
            "by_program": self._by_program(graduating),
            "top_skill_gaps": self._top_gaps(),
            "top_employers": self._top_employers(),
            "events": self._event_attendance(),
        }

    def _by_program(self, graduating: list[str]) -> list[dict]:
        rows = []
        groups: dict[tuple[str, str], list[str]] = defaultdict(list)
        for sid, s in self.students.items():
            groups[(s.get("college") or "Unassigned", s.get("major") or "Undeclared")].append(sid)
        grad_set = set(graduating)
        for (college, major), ids in sorted(groups.items()):
            reports = [self.outcomes[sid] for sid in ids if sid in grad_set and sid in self.outcomes]
            employed = [o for o in reports if o.get("outcome_type") == "full_time"]
            strengths = [self.store.plan_summaries[sid]["profile_strength"] for sid in ids
                         if sid in self.store.plan_summaries and "profile_strength" in self.store.plan_summaries[sid]]
            gaps = Counter(g for sid in ids for g in self.store.plan_summaries.get(sid, {}).get("skill_gaps", []))
            placement = _rate(sum(o.get("outcome_type") in POSITIVE_OUTCOMES for o in reports), len(reports))
            degree_level = _rate(sum(bool(o.get("degree_required")) for o in employed), len(employed))
            watch = []
            if len(reports) >= 5 and placement is not None and placement < 70:
                watch.append("Placement below 70%")
            if len(employed) >= 5 and degree_level is not None and degree_level < 60:
                watch.append("Degree-level jobs below 60%")
            rows.append({
                "college": college,
                "major": major,
                "students": len(ids),
                "activation_rate": _rate(sum(bool(self._by_student.get(sid)) for sid in ids), len(ids)),
                "avg_profile_strength": round(sum(strengths) / len(strengths)) if strengths else None,
                "outcomes_reported": len(reports),
                "placement_rate": placement,
                "degree_level_rate": degree_level,
                "top_gap": gaps.most_common(1)[0][0] if gaps else None,
                "watchlist": watch,
            })
        return rows

    def _top_gaps(self, limit: int = 8) -> list[dict]:
        gaps = Counter(g for sid in self.students for g in self.store.plan_summaries.get(sid, {}).get("skill_gaps", []))
        return [{"skill": skill, "students": count} for skill, count in gaps.most_common(limit)]

    def _top_employers(self, limit: int = 8) -> list[dict]:
        employers = Counter(o["employer"] for o in self.outcomes.values()
                            if o.get("employer") and o.get("outcome_type") in {"full_time", "internship"})
        return [{"employer": name, "hires": count} for name, count in employers.most_common(limit)]

    def _event_attendance(self) -> list[dict]:
        counts = Counter(c["event_id"] for c in self.event_checkins)
        rows = [{**{k: e.get(k) for k in ("id", "title", "host", "location", "starts_at")},
                 "check_ins": counts.get(eid, 0)} for eid, e in self.events.items()]
        return sorted(rows, key=lambda r: r["starts_at"] or "", reverse=True)

    # ── Caseload & brief ────────────────────────────────────────────────

    def caseload(self, priority: str | None = None, limit: int = 200) -> list[dict]:
        rows = []
        for sid, s in self.students.items():
            flags = self.risk_flags(sid)
            last = self.last_active(sid)
            rows.append({
                "student_id": sid,
                "name": s.get("name") or f"Student {sid[:8]}",
                "major": s.get("major"),
                "year": s.get("year"),
                "graduation_date": s.get("graduation_date"),
                "engagement_score": self.engagement_score(sid),
                "last_active": last.isoformat() if last else None,
                "outcome": OUTCOME_LABELS.get((self.outcomes.get(sid) or {}).get("outcome_type"), None),
                "flags": flags,
                "priority": self.priority(flags),
            })
        order = {"high": 0, "medium": 1, "low": 2}
        if priority:
            rows = [r for r in rows if r["priority"] == priority]
        rows.sort(key=lambda r: (order[r["priority"]], -len(r["flags"]), r["engagement_score"]))
        return rows[:limit]

    def brief(self, student_id: str) -> dict | None:
        student = self.students.get(student_id)
        if not student:
            return None
        counts = self.activity_counts(student_id)
        summary = self.store.plan_summaries.get(student_id, {})
        flags = self.risk_flags(student_id)
        attended = [self.events[c["event_id"]]["title"] for c in self.checkins if c["student_id"] == student_id]
        outcome = self.outcomes.get(student_id)
        last = self.last_active(student_id)
        return {
            "student": {
                "id": student_id,
                "name": student.get("name") or f"Student {student_id[:8]}",
                "major": student.get("major"),
                "college": student.get("college"),
                "year": student.get("year"),
                "graduation_date": student.get("graduation_date"),
                "gpa": student.get("gpa"),
                "first_generation": student.get("first_generation"),
                "career_interests": student.get("career_interests", []),
                "goal": student.get("short_term_goal") or student.get("current_goal"),
                "skills": (student.get("skills") or [])[:10],
            },
            "plan": {
                "profile_strength": summary.get("profile_strength"),
                "resume_score": summary.get("resume_score"),
                "top_matches": summary.get("top_matches", [])[:3],
                "skill_gaps": summary.get("skill_gaps", [])[:5],
                "generated_at": summary.get("generated_at"),
            },
            "engagement": {
                "score": self.engagement_score(student_id),
                "last_active": last.isoformat() if last else None,
                "resume_analyses": counts["resume_analyzed"],
                "interview_practices": counts["interview_practiced"],
                "missions_added": counts["mission_added"],
                "missions_completed": counts["mission_completed"],
                "events_attended": attended,
            },
            "outcome": outcome,
            "flags": flags,
            "priority": self.priority(flags),
            "talking_points": self._talking_points(student, summary, counts, flags, outcome),
            "review_note": "Suggestions are rule-based prompts for the advisor. The advisor decides what to recommend.",
        }

    @staticmethod
    def _talking_points(student: dict, summary: dict, counts: Counter, flags: list[str], outcome: dict | None) -> list[str]:
        points = []
        gaps = summary.get("skill_gaps") or []
        matches = summary.get("top_matches") or []
        if "Graduating with no outcome reported" in flags:
            points.append("Ask about current offers or applications and record the first-destination outcome.")
        if outcome and outcome.get("outcome_type") == "still_seeking":
            points.append("Review the application pipeline and set two applications per week as a mission.")
        if "Employed in a role that may not need a degree" in flags:
            points.append("Discuss a path from the current job to a degree-level role in the student's field.")
        if gaps:
            points.append(f"Pick one gap to close this month: {gaps[0]}. Link a campus workshop or certification.")
        if counts["interview_practiced"] == 0:
            points.append("Schedule a Rowdy mock interview before the next career fair.")
        if summary.get("resume_score") is not None and summary["resume_score"] < 60:
            points.append("Walk through the resume fixes for the student's top target role.")
        if matches:
            top = matches[0]
            points.append(f"Review the top match: {top.get('title')} at {top.get('organization')} ({top.get('match_score')}% fit).")
        if counts["event_checkin"] == 0:
            points.append("Suggest one upcoming campus event that fits the student's target role.")
        if student.get("first_generation"):
            points.append("First-generation student: offer alumni or peer mentor introductions.")
        return points[:6] or ["Student is on track. Confirm goals and next milestone."]

    # ── Export ───────────────────────────────────────────────────────────

    def outcomes_csv(self) -> str:
        buffer = io.StringIO()
        writer = csv.writer(buffer)
        writer.writerow([
            "student_id", "name", "college", "major", "year", "graduation_date", "outcome", "employer",
            "title", "degree_required", "salary", "reported_at", "source", "engagement_score", "events_attended",
        ])
        attended = Counter(c["student_id"] for c in self.checkins)
        for sid, outcome in sorted(self.outcomes.items()):
            s = self.students[sid]
            writer.writerow([
                sid, s.get("name") or "", s.get("college") or "", s.get("major") or "", s.get("year") or "",
                s.get("graduation_date") or "", OUTCOME_LABELS.get(outcome.get("outcome_type"), outcome.get("outcome_type")),
                outcome.get("employer") or "", outcome.get("title") or "",
                "yes" if outcome.get("degree_required") else "no", outcome.get("salary") or "",
                outcome.get("reported_at") or "", outcome.get("source") or "self_report",
                self.engagement_score(sid), attended.get(sid, 0),
            ])
        return buffer.getvalue()
